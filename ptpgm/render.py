"""Pure functions that turn a validated config into daemon config files."""

POLARITY = {"rising": "rising", "falling": "falling", "both": "both"}


def ptp4l_gm(cfg):
    t = cfg["ptp"]
    return f"""# Generated by ptp-gm - do not edit, change settings in the web UI
[global]
domainNumber            {t['domain']}
network_transport       {t['transport']}
delay_mechanism         {t['delay_mechanism']}
time_stamping           {t['time_stamping']}
clock_type              OC
masterOnly              1
priority1               {t['priority1']}
priority2               {t['priority2']}
clockClass              {t['clock_class']}
clockAccuracy           {t['clock_accuracy']}
timeSource              {t['time_source']}
utc_offset              {t['utc_offset']}
logAnnounceInterval     {t['log_announce_interval']}
logSyncInterval         {t['log_sync_interval']}
logMinDelayReqInterval  {t['log_min_delay_req_interval']}
# The PHC is steered by ts2phc, ptp4l must not touch it.
free_running            1
use_syslog              1
verbose                 0
logging_level           6
uds_address             /var/run/ptp4l
summary_interval        0

[{t['interface']}]
"""


def ptp4l_measure(cfg):
    m = cfg["measure"]
    free = 1 if m["free_running"] else 0
    return f"""# Generated by ptp-gm - do not edit, change settings in the web UI
[global]
domainNumber            {m['domain']}
network_transport       {m['transport']}
delay_mechanism         {m['delay_mechanism']}
time_stamping           {m['time_stamping']}
clock_type              OC
clientOnly              1
free_running            {free}
use_syslog              1
verbose                 0
logging_level           6
uds_address             /var/run/ptp4l
summary_interval        0

[{m['interface']}]
"""


def ts2phc(cfg):
    p = cfg["pps"]
    lines = [
        "# Generated by ptp-gm - do not edit, change settings in the web UI",
        "[global]",
        "use_syslog              0",
        "verbose                 1",
        "logging_level           6",
        "ts2phc.pulsewidth       100000000",
        "ts2phc.leapfile         /usr/share/zoneinfo/leap-seconds.list",
    ]
    if p["source"] == "nmea":
        lines += [
            "ts2phc.nmea_remote_host 127.0.0.1",
            "ts2phc.nmea_remote_port 2947",
        ]
    lines += [
        "",
        f"[{p['interface']}]",
        f"ts2phc.channel          {p['channel']}",
        f"ts2phc.pin_index        {p['pin']}",
        f"ts2phc.extts_polarity   {POLARITY[p['polarity']]}",
        f"ts2phc.extts_correction {p['correction_ns']}",
        "",
    ]
    return "\n".join(lines)


def gpsd_default(cfg):
    g = cfg["gps"]
    return f"""# Generated by ptp-gm
START_DAEMON="true"
USBAUTO="false"
DEVICES="{g['device']}"
GPSD_OPTIONS="-n -s {g['baud']}"
"""


def chrony_snippet(cfg):
    allow = cfg["system"]["ntp_allow"]
    out = ["# Generated by ptp-gm",
           "# The system clock is disciplined by phc2sys from the GPS-locked PHC;",
           "# chrony only serves it.",
           "local stratum 1",
           "refid GPS"]
    if allow:
        out.append(f"allow {allow}")
    return "\n".join(out) + "\n"


def phc2sys_args(cfg):
    return ["-s", cfg["ptp"]["interface"], "-c", "CLOCK_REALTIME", "-w", "-m"]
