"""Pure functions that turn a validated config into daemon config files."""

POLARITY = {"rising": "rising", "falling": "falling", "both": "both"}


def ptp4l_gm(cfg):
    t = cfg["ptp"]
    return f"""# Generated by ptp-gm - do not edit, change settings in the web UI
[global]
domainNumber            {t['domain']}
network_transport       {t['transport']}
delay_mechanism         {t['delay_mechanism']}
time_stamping           {t['time_stamping']}
clock_type              OC
serverOnly              1
priority1               {t['priority1']}
priority2               {t['priority2']}
clockClass              {t['clock_class']}
clockAccuracy           {t['clock_accuracy']}
timeSource              {t['time_source']}
utc_offset              {t['utc_offset']}
announceReceiptTimeout  {t['announce_receipt_timeout']}
tx_timestamp_timeout    100
offsetScaledLogVariance 0x4e5d
logAnnounceInterval     {t['log_announce_interval']}
logSyncInterval         {t['log_sync_interval']}
logMinDelayReqInterval  {t['log_min_delay_req_interval']}
# The PHC is steered by ts2phc, ptp4l must not touch it.
free_running            1
use_syslog              1
verbose                 0
logging_level           6
uds_address             /var/run/ptp4l
summary_interval        0

[{t['interface']}]
"""


