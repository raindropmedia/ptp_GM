def ts2phc(cfg):
    p = cfg["pps"]
    lines = [
        "# Generated by ptp-gm - do not edit, change settings in the web UI",
        "[global]",
        "use_syslog              0",
        "verbose                 1",
        "logging_level           6",
        f"ts2phc.pulsewidth       {cfg['pps']['pulsewidth_ns']}",
        "leapfile                /usr/share/zoneinfo/leap-seconds.list",
    ]
    if p["source"] == "nmea":
        lines += [
            "ts2phc.nmea_remote_host 127.0.0.1",
            "ts2phc.nmea_remote_port 2948",  # ptpgm-nmea relay, see nmea_relay.py
        ]
    lines += [
        "",
        f"[{p['interface']}]",
        f"ts2phc.channel          {p['channel']}",
        f"ts2phc.pin_index        {p['pin']}",
        f"ts2phc.extts_polarity   {POLARITY[p['polarity']]}",
        f"ts2phc.extts_correction {p['correction_ns']}",
        "",
    ]
    return "\n".join(lines)


def gpsd_default(cfg):
    g = cfg["gps"]
    return f"""# Generated by ptp-gm
START_DAEMON="true"
USBAUTO="false"
DEVICES="{g['device']}"
GPSD_OPTIONS="-n -s {g['baud']}"
"""


def chrony_snippet(cfg, phc_index=None, phc_enabled=False, subnets=()):
    """chrony config. The PHC refclock is only included while ts2phc has the PHC locked to
    GPS (the web service switches it), so chrony never follows a free-running PHC."""
    sysc = cfg["system"]
    out = ["# Generated by ptp-gm - do not edit",
           "# NMEA time from gpsd (coarse, ~100 ms): shown for comparison, never used to steer",
           "refclock SHM 0 refid NMEA precision 1e-1 noselect"]
    if phc_enabled and phc_index is not None:
        out += ["# GPS-locked hardware clock of the I210 (TAI), steers the system clock",
                f"refclock PHC /dev/ptp{phc_index} tai poll 0 dpoll -2 refid GPS prefer"]
    if sysc["ntp_server"]:
        # without any "allow" chrony does not answer NTP clients at all
        nets = [sysc["ntp_allow"]] if sysc["ntp_allow"] else list(subnets)
        out += [f"allow {n}" for n in nets]
    return "\n".join(out) + "\n"


def phc2sys_args(cfg):
    return ["-s", cfg["ptp"]["interface"], "-c", "CLOCK_REALTIME", "-w", "-m"]
